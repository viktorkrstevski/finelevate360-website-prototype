"""Build an allowlisted, versioned WordPress theme artifact without site data."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import stat
import zipfile

SLUG = "finelevate-advisory"
HOST = "stg.finelevate360.com"
SOURCE = Path("wordpress/themes") / SLUG
ALLOWED = {".php", ".css", ".js", ".json", ".svg", ".png", ".jpg", ".jpeg", ".webp", ".avif", ".woff", ".woff2", ".ttf", ".txt"}
REQUIRED = {"style.css", "functions.php", "index.php"}
FORBIDDEN = re.compile(r"(^|/)(?:\.git|\.env(?:\..*)?|wp-config\.php|uploads|node_modules|vendor|.*\.(?:sql|sqlite|pem|key|p12|pfx))($|/)", re.I)


def check_image_metadata(name, data):
    """Reject personal image metadata rather than silently publishing it."""
    if data.startswith(b'\xff\xd8'):
        position = 2
        while position + 4 <= len(data):
            if data[position] != 255:
                raise ValueError(f"Malformed JPEG: {name}")
            marker = data[position + 1]
            if marker in (218, 217):
                break
            length = int.from_bytes(data[position + 2:position + 4], 'big')
            if marker in (225, 237, 254):
                raise ValueError(f"Remove JPEG EXIF/XMP/IPTC/comments before packaging: {name}")
            if length < 2:
                raise ValueError(f"Malformed JPEG marker: {name}")
            position += 2 + length
    elif data.startswith(b'\x89PNG\r\n\x1a\n'):
        position = 8
        while position + 12 <= len(data):
            length = int.from_bytes(data[position:position + 4], 'big')
            if data[position + 4:position + 8] in (b'eXIf', b'tEXt', b'iTXt', b'zTXt'):
                raise ValueError(f"Remove PNG metadata before packaging: {name}")
            position += 12 + length
    elif data[:4] == b'RIFF' and data[8:12] == b'WEBP':
        position = 12
        while position + 8 <= len(data):
            length = int.from_bytes(data[position + 4:position + 8], 'little')
            if data[position:position + 4] in (b'EXIF', b'XMP '):
                raise ValueError(f"Remove WebP metadata before packaging: {name}")
            position += 8 + length + (length % 2)


def theme_files(source):
    source = Path(source)
    files = []
    for file in sorted(source.rglob("*")):
        relative = file.relative_to(source).as_posix()
        if file.is_symlink() or FORBIDDEN.search(relative):
            raise ValueError(f"Forbidden theme artifact path: {relative}")
        if file.is_dir():
            continue
        if not file.is_file() or file.suffix.lower() not in ALLOWED:
            raise ValueError(f"Unapproved artifact file: {relative}")
        if file.stat().st_size > 12 * 1024 * 1024:
            raise ValueError(f"Oversized theme file: {relative}")
        data = file.read_bytes()
        check_image_metadata(relative, data)
        files.append((relative, data))
    if not REQUIRED.issubset({name for name, _ in files}):
        raise ValueError("Theme must include style.css, functions.php and index.php")
    if any(name == "release.json" for name, _ in files):
        raise ValueError("release.json is generated by CI, not checked in")
    if sum(len(data) for _, data in files) > 50 * 1024 * 1024:
        raise ValueError("Theme exceeds the 50 MiB artifact limit")
    return files


def build(source, output, commit):
    if not re.fullmatch(r"[a-f0-9]{40}", commit):
        raise ValueError("A full Git commit SHA is required")
    files = theme_files(source)
    manifest = {"schema": 1, "host": HOST, "theme": SLUG, "commit": commit,
                "files": {name: hashlib.sha256(data).hexdigest() for name, data in files}}
    files.append(("release.json", (json.dumps(manifest, sort_keys=True, indent=2) + "\n").encode()))
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in files:
            info = zipfile.ZipInfo(f"{SLUG}/{name}", date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (stat.S_IFREG | 0o644) << 16
            archive.writestr(info, data)
    digest = hashlib.sha256(output.read_bytes()).hexdigest()
    output.with_suffix(".zip.sha256").write_text(f"{digest}  {output.name}\n")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--output", type=Path, default=Path("artifacts/finelevate-advisory.zip"))
    args = parser.parse_args()
    build(args.source, args.output, args.commit)
    print(f"Packaged {SLUG} at {args.commit} for {HOST}")
